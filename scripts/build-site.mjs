// 4. Safety check: the private app path must not appear anywhere public.
for (const f of ['index.html', 'robots.txt', 'demo/index.html', 'demo/manifest.webmanifest', 'demo/sw.js']) {
  if (fs.readFileSync(path.join(OUT, f), 'utf8').includes(cfg.appPath)) throw new Error(`The private app path leaked into ${f}`);
}
fs.rmSync(TMP, { recursive: true, force: true });

console.log(`\nsite/ ready for Cloudflare Pages:
  /                  landing (links to /demo/ and Etsy only)
  /demo/             demo        (sw ${demoVersion})
  /${cfg.appPath}/  full app    (sw ${appVersion})  ← private: give customers ${cfg.siteUrl}/${cfg.appPath}/`);
